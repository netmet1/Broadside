// Controls that have their own use for Enter. Return on one of these is left
// alone; Return anywhere else in a dialog presses its remembered button.
const OWNS_ENTER = [
  "button",
  "input",
  "textarea",
  "select",
  "a[href]",
  "[contenteditable]:not([contenteditable=false])",
  "[role]:not([role=dialog]):not([role=alertdialog]):not([role=group]):not([role=presentation]):not([role=none])",
  "[tabindex]:not([tabindex='-1'])",
].join(",")

function isPlainButton(el: EventTarget): el is HTMLButtonElement {
  if (!(el instanceof HTMLButtonElement)) return false
  const role = el.getAttribute("role")
  return role === null || role === "button"
}

function AlertDialogContent({
  className,
  size = "default",
  onFocus,
  onKeyDown,
  ...props
}: React.ComponentProps<typeof AlertDialogPrimitive.Content> & {
  size?: "default" | "sm"
}) {
  // The button that last had the focus in this dialog: Cancel as it opens,
  // unless Tab moved on. A click on the text or the checkbox's label moves the
  // focus to the dialog itself, where Enter does nothing, so Return presses
  // this button instead, as it would have before the click. It never presses
  // a button that has not had the focus.
  const lastButton = React.useRef<HTMLButtonElement | null>(null)

  return (
    <AlertDialogPortal>
      {/* A click on the dark area behind the dialog keeps the focus where it
          was, rather than dropping it on the page, out of the dialog's reach. */}
      <AlertDialogOverlay onMouseDown={(e) => e.preventDefault()} />
      <AlertDialogPrimitive.Content
        data-slot="alert-dialog-content"
        data-size={size}
        onFocus={(e) => {
          onFocus?.(e)
          if (isPlainButton(e.target) && e.currentTarget.contains(e.target)) {
            lastButton.current = e.target
          }
        }}
        onKeyDown={(e) => {
          onKeyDown?.(e)
          if (e.defaultPrevented || e.key !== "Enter" || e.repeat) return
          if (e.ctrlKey || e.altKey || e.metaKey || e.nativeEvent.isComposing) {
            return
          }
          const content = e.currentTarget
          const target = e.target as Element
          if (!content.contains(target)) return
          if (target !== content && target.closest(OWNS_ENTER)) return
          const remembered = lastButton.current
          const button =
            remembered && content.contains(remembered) && !remembered.disabled
              ? remembered
              : content.querySelector<HTMLButtonElement>(
                  "[data-slot=alert-dialog-cancel]"
                )
          if (!button || button.disabled) return
          e.preventDefault()
          button.click()
        }}
        className={cn(
          "group/alert-dialog-content fixed top-1/2 left-1/2 z-50 grid w-full -translate-x-1/2 -translate-y-1/2 gap-4 rounded-xl bg-popover p-4 text-popover-foreground ring-1 ring-foreground/10 duration-100 outline-none data-[size=default]:max-w-xs data-[size=sm]:max-w-xs data-[size=default]:sm:max-w-sm data-open:animate-in data-open:fade-in-0 data-open:zoom-in-95 data-closed:animate-out data-closed:fade-out-0 data-closed:zoom-out-95",
          className
        )}
        {...props}
      />
    </AlertDialogPortal>
  )
}

