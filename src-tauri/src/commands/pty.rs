#[cfg(test)]
mod tests {
    use super::should_autofill_sudo;

    #[test]
    fn autofill_gated_by_global_toggle() {
        // Normal case: toggle on, stored password, non-root → inject.
        assert!(should_autofill_sudo(true, true, "deploy"));
        // Toggle off → never inject even with a stored password (the new gate).
        assert!(!should_autofill_sudo(false, true, "deploy"));
        // No stored password → nothing to inject.
        assert!(!should_autofill_sudo(true, false, "deploy"));
        // root has no sudo prompt; case-insensitive.
        assert!(!should_autofill_sudo(true, true, "root"));
        assert!(!should_autofill_sudo(true, true, "ROOT"));
    }
}
